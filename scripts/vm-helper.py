#!/usr/bin/env python3
"""Build a camareLOL test profile from a device survey.

Used by the VirtualBox acceptance test: the VM scans its empty disk, this
script turns the survey into a profile the installer can run headlessly.
"""

from __future__ import annotations

import json
import os
import sys
from pathlib import Path


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: vm-helper.py <survey.json> <profile.toml>", file=sys.stderr)
        return 2

    # Desktop runs the profile through these. The console-only default is what
    # CI has always checked; setting a desktop profile makes the acceptance run
    # verify the display stack instead of assuming it works.
    desktop = os.environ.get("CAMARELOL_TEST_DESKTOP", "console")
    display_server = os.environ.get("CAMARELOL_TEST_DISPLAY_SERVER", "auto")
    display_manager = os.environ.get("CAMARELOL_TEST_DISPLAY_MANAGER", "")
    printing = os.environ.get("CAMARELOL_TEST_PRINTING", "false")

    survey_path, profile_path = Path(sys.argv[1]), Path(sys.argv[2])
    devices = json.loads(survey_path.read_text(encoding="utf-8"))

    # A dual-boot run (CAMARELOL_TEST_DUAL_BOOT=1) targets a disk that already
    # carries "Windows-shaped" partitions made by scripts/vm-dualboot.sh,
    # instead of the first empty disk, and the profile switches the planner
    # to keep-everything mode (reuse_esp = true).
    dual_boot = os.environ.get("CAMARELOL_TEST_DUAL_BOOT", "") == "1"
    target = None
    if dual_boot:
        for device in devices:
            if (
                device.get("partition_table") == "Gpt"
                and device.get("partitions")
                and device.get("mount_state", "NotMounted") == "NotMounted"
                # Exclude the disk the live system runs from (mounted) and any
                # disk that a real flagged-Windows survey marked. Note: a
                # "WindowsRecovery" hint alone is fine — the fake disk carries
                # a recovery-shaped partition by design.
                and "Windows" not in [str(h) for h in device.get("os_hints", [])]
            ):
                target = device
                break
        if target is None:
            print(
                "error: no GPT disk with kept partitions found in the survey",
                file=sys.stderr,
            )
            return 1
        keep_line = 'reuse_esp = true\n'
    else:
        for device in devices:
            if device.get("partition_table") == "None" and not device.get("partitions"):
                target = device
                break
        if target is None:
            print("error: no empty disk found in the survey", file=sys.stderr)
            return 1
        keep_line = ""

    # `identity` is a method on the Rust side; the survey only carries the raw
    # fields, so we reconstruct it here (WWN > serial > kernel name).
    identity = target.get("wwn") or target.get("serial") or target.get("kernel_name")

    # A console-only install cannot carry a display manager (preflight refuses
    # that pairing), so the line is omitted rather than written empty — an empty
    # string would deserialize to Some("") and fail validation.
    display_manager_line = (
        f'display_manager = "{display_manager}"\n' if display_manager else ""
    )

    profile = f"""# Generated by vm-helper.py — do not edit by hand.
schema_version = 1
language = "en"
system_locale = "en_US.UTF-8"
keymap = "us"
timezone = "UTC"
firmware = "auto"
target_disk = {{ path = "{target['path']}", identity = "{identity}", size_bytes = {target['size_bytes']} }}
filesystem = "ext4"
separate_boot = false
separate_home = false
{keep_line}bootloader = "grub"
desktop = "{desktop}"
display_server = "{display_server}"
{display_manager_line}hostname = "camarelol-vm"
root_login_allowed = true
users = []
admin_users = []

[packages]
core = ["base", "linux", "linux-firmware", "base-devel", "sudo", "networkmanager", "vim", "man-db", "man-pages"]
utilities = []
drivers_firmware = []
user_selected = []
aur_packages = []
aur_enabled = false

[services]
# ssh = true để bài kiểm tra chạm cả hai bản vá: openssh phải có thật khi
# sshd được bật, và zram-generator.conf phải có thật khi zram được bật.
audio = "pipewire"
network_manager = true
bluetooth = false
printing = {printing}
ssh = true
zram = true
"""
    profile_path.write_text(profile, encoding="utf-8")
    print(f"wrote {profile_path} targeting {target['path']} ({identity})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
