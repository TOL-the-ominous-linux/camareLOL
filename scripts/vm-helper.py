#!/usr/bin/env python3
"""Build a camareLOL test profile from a device survey.

Used by the VirtualBox acceptance test: the VM scans its empty disk, this
script turns the survey into a profile the installer can run headlessly.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: vm-helper.py <survey.json> <profile.toml>", file=sys.stderr)
        return 2

    survey_path, profile_path = Path(sys.argv[1]), Path(sys.argv[2])
    devices = json.loads(survey_path.read_text(encoding="utf-8"))

    # Pick the first disk that is empty (no partition table, no partitions).
    target = None
    for device in devices:
        if device.get("partition_table") == "None" and not device.get("partitions"):
            target = device
            break
    if target is None:
        print("error: no empty disk found in the survey", file=sys.stderr)
        return 1

    # `identity` is a method on the Rust side; the survey only carries the raw
    # fields, so we reconstruct it here (WWN > serial > kernel name).
    identity = target.get("wwn") or target.get("serial") or target.get("kernel_name")

    profile = f"""# Generated by vm-helper.py — do not edit by hand.
schema_version = 1
language = "en"
system_locale = "en_US.UTF-8"
keymap = "us"
timezone = "UTC"
firmware = "auto"
target_disk = {{ path = "{target['path']}", identity = "{identity}", size_bytes = {target['size_bytes']} }}
filesystem = "ext4"
separate_boot = false
separate_home = false
swap_bytes = null
bootloader = "grub"
desktop = "console"
display_server = "auto"
hostname = "camarelol-vm"
root_login_allowed = true
users = []
admin_users = []
"""
    profile_path.write_text(profile, encoding="utf-8")
    print(f"wrote {profile_path} targeting {target['path']} ({identity})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
